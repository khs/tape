/**
 * Builds the full chart-library manifest consumed by the composer and the
 * client-side renderers. Extracted from src/pages/library.json.ts so the
 * manifest can be partitioned into two prerendered payloads without
 * duplicating ~400 lines of synthesis logic:
 *
 *   - /library.json      (lean): visible-by-default sources + hint cards +
 *                                charts + metros/countries lookups +
 *                                tagCountsByGeo. ~2 MB.
 *   - /library-geo.json  (geo):  the hidden-by-default geo source block
 *                                (CD / state / metro / county / country),
 *                                ~37 MB, lazy-loaded by the client only when
 *                                a geo chip is engaged or a >=4-char query
 *                                unlocks them. See src/lib/library-loader.ts.
 *
 * `buildLibraryManifest()` is memoized at module scope so the two endpoints
 * that slice it (library.json.ts + library-geo.json.ts) share one build pass
 * within a single prerender — the heavy work (getCollection + tag synthesis
 * over ~30k sources) runs once, not twice.
 *
 * The build-time empty-selector invariants + the hint synthesis run over the
 * FULL source set inside this builder (before the lean/geo partition), so the
 * split can't smuggle an empty chip dropdown past the guard.
 */
