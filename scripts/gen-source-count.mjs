/**
 * Generate src/lib/source-count.ts — the single source of truth for the
 * coverage numbers shown in marketing copy ("N+ sources", "393 US
 * metros", "54 countries" on the homepage / welcome page).
 *
 * Counts at build time and writes cheap constants, so:
 *   - the figures are always CURRENT as of each deploy (the data-refresh
 *     workflows that add sources trigger a rebuild, which re-runs this),
 *   - it's ONE place to change rounding/format, and
 *   - SSR pages (the homepage is prerender=false) import plain constants
 *     instead of calling getCollection() per request.
 *
 * Run from `prebuild`. The committed output is a fallback for typecheck +
 * any build that doesn't run the prebuild hook.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCES_DIR = "src/content/sources";
const OUT = "src/lib/source-count.ts";

function countYaml(dir) {
  let n = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) n += countYaml(p);
    else if (entry.name.endsWith(".yaml")) n += 1;
  }
  return n;
}

const count = countYaml(SOURCES_DIR);
// Floor to the nearest 1,000 and append "+", so the marketing figure is
// never an overstatement and grows automatically as the library does.
const floored = Math.floor(count / 1000) * 1000;
const display = `${floored.toLocaleString("en-US")}+`;
// Same floored figure without the "+", for copy that supplies its own
// qualifier (e.g. "over 38,000 sources"), where "38,000+" would double up.
const roundedDisplay = floored.toLocaleString("en-US");

/* ---- US metros: distinct CBSA codes across the metro pipelines ----
 * Every metro-keyed source carries its 5-digit CBSA code in the
 * filename (acs_metro/bls: trailing `_NNNNN.yaml`; usaspending:
 * `metro_NNNNN.yaml`). The union across pipelines is the honest
 * "how many metros do we cover at all" number. */
function listYaml(dir) {
  try {
    return readdirSync(join(SOURCES_DIR, dir)).filter((f) => f.endsWith(".yaml"));
  } catch {
    return [];
  }
}
const metroCbsas = new Set();
for (const f of listYaml("acs_metro")) {
  const m = /_(\d{5})\.yaml$/.exec(f);
  if (m) metroCbsas.add(m[1]);
}
for (const f of listYaml("bls")) {
  const m = /_(\d{5})\.yaml$/.exec(f);
  if (m) metroCbsas.add(m[1]);
}
for (const f of listYaml("usaspending")) {
  const m = /^metro_(\d{5})\.yaml$/.exec(f);
  if (m) metroCbsas.add(m[1]);
}
const metroCount = metroCbsas.size;

/* ---- Countries: distinct country names in worldbank_extended ----
 * worldbank_extended is the broadest per-country catalog (it spans
 * every other international pipeline's membership — the 38 OECD
 * members are a verified subset). Names come from the YAML `name:`
 * suffix ("<indicator> — <Country>"). World Bank REGION aggregates
 * are excluded — they're rollups, not countries. Counts territories
 * with their own data (Bermuda, Hong Kong, Cayman Islands). */
const WB_REGION_AGGREGATES = new Set([
  "East Asia and Pacific",
  "Europe and Central Asia",
  "European Union",
  "Latin America and Caribbean",
  "Middle East and North Africa",
  "North America",
  "South Asia",
  "Sub-Saharan Africa",
]);
const countryNames = new Set();
for (const f of listYaml("worldbank_extended")) {
  const text = readFileSync(join(SOURCES_DIR, "worldbank_extended", f), "utf8");
  const nameLine = text.split("\n").find((l) => l.startsWith("name:"));
  const m = nameLine && /—\s*(.+?)"?\s*$/.exec(nameLine);
  if (!m) continue;
  const name = m[1].trim().replace(/"$/, "");
  if (!WB_REGION_AGGREGATES.has(name)) countryNames.add(name);
}
const countryCount = countryNames.size;

const body =
  `// AUTO-GENERATED by scripts/gen-source-count.mjs (runs in prebuild).\n` +
  `// Do not edit by hand -- change the rounding/format in that script.\n` +
  `// Counts under src/content/sources as of the last build.\n` +
  `\n` +
  `/** Exact source count at build time. */\n` +
  `export const SOURCE_COUNT = ${count};\n` +
  `\n` +
  `/** Marketing figure, floored to the nearest 1,000 with a "+", e.g. "${display}". */\n` +
  `export const SOURCE_COUNT_DISPLAY = ${JSON.stringify(display)};\n` +
  `\n` +
  `/** Same floored figure without the "+", for copy that adds its own qualifier\n` +
  ` *  (e.g. "over ${roundedDisplay} sources"), where "${display}" would double up. */\n` +
  `export const SOURCE_COUNT_ROUNDED = ${JSON.stringify(roundedDisplay)};\n` +
  `\n` +
  `/** Distinct CBSA codes across the metro pipelines (acs_metro, bls, usaspending). */\n` +
  `export const METRO_COUNT = ${metroCount};\n` +
  `\n` +
  `/** Distinct countries/territories in worldbank_extended (region aggregates excluded;\n` +
  ` *  the 38 OECD members are a subset). */\n` +
  `export const COUNTRY_COUNT = ${countryCount};\n`;

writeFileSync(OUT, body, "utf8");
console.log(
  `[source-count] ${count} source YAMLs -> ${display}; ` +
  `${metroCount} metros; ${countryCount} countries (wrote ${OUT})`,
);
